	/**
	 * A tolerant {@link IXmlReader#parseInteger(NamedNodeMap, String, Integer)}, since this file is meant to be hand tuned : a stray space around a value would otherwise throw, and take the whole
	 * server startup down with it.
	 * @param attrs : The attributes to read.
	 * @param name : The attribute name to read.
	 * @param defaultValue : The value returned when the attribute is missing, empty or not a number.
	 * @return The parsed value.
	 */
	private int parseInt(NamedNodeMap attrs, String name, int defaultValue)
	{
		final String value = parseTrimmed(attrs, name);
		if (value == null)
			return defaultValue;

		try
		{
			return Integer.parseInt(value);
		}
		catch (NumberFormatException e)
		{
			LOGGER.warn("The drop list attribute '{}' holds '{}', which isn't a number ; {} is used instead.", name, value, defaultValue);
			return defaultValue;
		}
	}

	/**
	 * Same as {@link IXmlReader#parseString(NamedNodeMap, String, String)}, minus the surrounding spaces - which would leak into a color and break the generated tag.
	 * @param attrs : The attributes to read.
	 * @param name : The attribute name to read.
	 * @param defaultValue : The value returned when the attribute is missing. An explicitly empty attribute stays empty.
	 * @return The trimmed value of the given attribute.
	 */
	private static String parseToken(NamedNodeMap attrs, String name, String defaultValue)
	{
		final Node node = attrs.getNamedItem(name);

		return (node == null) ? defaultValue : node.getNodeValue().trim();
	}

	/**
	 * @param attrs : The attributes to read.
	 * @param name : The attribute name to read.
	 * @return The trimmed value of the given attribute, null if it is missing or blank.
	 */
	private static String parseTrimmed(NamedNodeMap attrs, String name)
	{
		final Node node = attrs.getNamedItem(name);
		if (node == null)
			return null;

		final String value = node.getNodeValue().trim();

		return (value.isEmpty()) ? null : value;
	}

	/**
	 * A group is only ever captioned "drop" or "spoil" : whether an item is looted or spoiled is the one thing the items sitting under the header can't tell a player, and the currency and herb
	 * groups are looted just like the regular ones. The rank of the group inside its own caption is appended, which is what tells two "drop" groups apart.
	 * @param type : The {@link DropType} to name.
	 * @param number : The rank of the group among the ones sharing its caption, 1 being the first.
	 * @return The caption of the header row of a group holding the given {@link DropType}, being "Drop #1" out of the box.
	 */
	public String getGroupLabel(DropType type, int number)
	{
		return ((type == DropType.SPOIL) ? _spoilLabel : _dropLabel) + _numberPrefix + number;
	}

	/**
	 * @return The caption of the header row of the group holding the extra drops of a champion monster. It doesn't carry any rank : a monster only ever owns one such group.
	 */
