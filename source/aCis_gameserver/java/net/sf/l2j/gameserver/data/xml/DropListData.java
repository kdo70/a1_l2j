	@Override
	public void load()
	{
		setDefaultLayout();
		setDefaultColors();
		setDefaultLabels();

		// IXmlReader only catches the parser exceptions ; without this, a single malformed attribute would abort the whole server startup.
		try
		{
			parseFile("./data/xml/droplist.xml");
		}
		catch (Exception e)
		{
			LOGGER.error("Couldn't fully read droplist.xml ; the drop list window runs on whatever has been read so far.", e);
		}
	}

	@Override
	public void parseDocument(Document doc, Path path)
	{
		forEach(doc, "list", listNode ->
		{
			forEach(listNode, "layout", layoutNode ->
			{
				final NamedNodeMap attrs = layoutNode.getAttributes();

				_width = Math.max(1, parseInt(attrs, "width", _width));
				_rowHeight = Math.max(1, parseInt(attrs, "rowHeight", _rowHeight));
				_groupHeight = Math.max(1, parseInt(attrs, "groupHeight", _groupHeight));
				_iconSize = Math.max(1, parseInt(attrs, "iconSize", _iconSize));
				_maxPages = Math.max(1, parseInt(attrs, "maxPages", _maxPages));
				_pageWidth = Math.max(1, parseInt(attrs, "pageWidth", _pageWidth));
				_pageHeight = Math.max(0, parseInt(attrs, "pageHeight", _pageHeight));
				_overhead = Math.max(0, parseInt(attrs, "overhead", _overhead));
				_nameChars = Math.max(0, parseInt(attrs, "nameChars", _nameChars));
				_ellipsis = parseString(attrs, "ellipsis", _ellipsis);
				_separator = parseToken(attrs, "separator", _separator);

				_headerHeight = Math.max(1, parseInt(attrs, "headerHeight", _headerHeight));
				_headerLabelWidth = Math.max(1, parseInt(attrs, "headerLabelWidth", _headerLabelWidth));
				_headerGap = Math.max(0, parseInt(attrs, "headerGap", _headerGap));

				_iconWidth = Math.max(1, parseInt(attrs, "iconWidth", _iconWidth));
				_nameWidth = Math.max(1, parseInt(attrs, "nameWidth", _nameWidth));
				_chanceWidth = Math.max(1, parseInt(attrs, "chanceWidth", _chanceWidth));

				final int total = _iconWidth + _nameWidth + _chanceWidth;
				if (total != _width)
					LOGGER.warn("The columns of the drop list layout sum up to {} instead of the layout width {} ; the rows won't be aligned.", total, _width);
			});

			forEach(listNode, "colors", colorsNode ->
			{
				final NamedNodeMap attrs = colorsNode.getAttributes();

				_highChance = Math.max(0, parseInt(attrs, "highChanceFrom", _highChance));
				_mediumChance = Math.max(0, parseInt(attrs, "mediumChanceFrom", _mediumChance));

				_rowColor = parseToken(attrs, "row", _rowColor);
				_altRowColor = parseToken(attrs, "altRow", _altRowColor);
				_groupTextColor = parseToken(attrs, "groupText", _groupTextColor);
				_headerTextColor = parseToken(attrs, "headerText", _headerTextColor);
				_headerValueColor = parseToken(attrs, "headerValue", _headerValueColor);
				_nameColor = parseToken(attrs, "name", _nameColor);
				_countColor = parseToken(attrs, "count", _countColor);
				_highChanceColor = parseToken(attrs, "highChance", _highChanceColor);
				_mediumChanceColor = parseToken(attrs, "mediumChance", _mediumChanceColor);
				_lowChanceColor = parseToken(attrs, "lowChance", _lowChanceColor);
				_disabledColor = parseToken(attrs, "disabled", _disabledColor);
				_pageColor = parseToken(attrs, "page", _pageColor);
				_activePageColor = parseToken(attrs, "activePage", _activePageColor);
			});

			forEach(listNode, "labels", labelsNode ->
			{
				final NamedNodeMap attrs = labelsNode.getAttributes();

				_dropLabel = parseString(attrs, "drop", _dropLabel);
				_spoilLabel = parseString(attrs, "spoil", _spoilLabel);
				_championLabel = parseString(attrs, "champion", _championLabel);
				_hpLabel = parseString(attrs, "hp", _hpLabel);
				_mpLabel = parseString(attrs, "mp", _mpLabel);
				_expLabel = parseString(attrs, "exp", _expLabel);
				_spLabel = parseString(attrs, "sp", _spLabel);
				_pAtkLabel = parseString(attrs, "pAtk", _pAtkLabel);
				_pDefLabel = parseString(attrs, "pDef", _pDefLabel);
				_atkSpdLabel = parseString(attrs, "atkSpd", _atkSpdLabel);
				_mAtkLabel = parseString(attrs, "mAtk", _mAtkLabel);
				_mDefLabel = parseString(attrs, "mDef", _mDefLabel);
				_castSpdLabel = parseString(attrs, "castSpd", _castSpdLabel);
				_numberPrefix = parseString(attrs, "numberPrefix", _numberPrefix);
				_countPrefix = parseString(attrs, "countPrefix", _countPrefix);
				_countRange = parseString(attrs, "countRange", _countRange);
				_chancePattern = parseToken(attrs, "chancePattern", _chancePattern);
				_chanceSuffix = parseString(attrs, "chanceSuffix", _chanceSuffix);
				_nearZeroLabel = parseString(attrs, "nearZero", _nearZeroLabel);
				_emptyLabel = parseString(attrs, "empty", _emptyLabel);
				_prevPageLabel = parseString(attrs, "prevPage", _prevPageLabel);
				_nextPageLabel = parseString(attrs, "nextPage", _nextPageLabel);
			});
		});
	}

