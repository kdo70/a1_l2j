	/** One entry of the level filter menu sitting on the head of the list. A range of 0 to 0 matches every raid boss, which is what the "all" entry is. */
	public record LevelFilter(String label, int min, int max)
	{
		public boolean matches(int level)
		{
			return (min <= 0 && max <= 0) || (level >= min && level <= max);
		}
	}

