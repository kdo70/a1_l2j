	/**
	 * The rows of a table are generated out of fixed column widths ; a set which doesn't sum up to the layout width simply doesn't align.
	 * @param name : The name of the checked table, used by the warning.
	 * @param total : The sum of the column widths of that table.
	 */
	private void checkColumns(String name, int total)
	{
		if (total != _width)
			LOGGER.warn("The {} columns of the raid boss book sum up to {} instead of the layout width {} ; the rows won't be aligned.", name, total, _width);
	}

