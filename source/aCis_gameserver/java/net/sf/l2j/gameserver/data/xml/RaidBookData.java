	public List<LevelFilter> getFilters()
	{
		return _filters;
	}

	/**
	 * @param index : The index of the wanted filter.
	 * @return The {@link LevelFilter} of the given index, the first one when the index is out of the list.
	 */
	public LevelFilter getFilter(int index)
	{
		return _filters.get((index < 0 || index >= _filters.size()) ? 0 : index);
	}

	/**
	 * @param chance : The already computed chance, in percent.
	 * @return The color the given chance is shown with.
	 */
	public String getChanceColor(double chance)
	{
		if (chance >= _highChance)
			return _highChanceColor;

		return (chance >= _mediumChance) ? _mediumChanceColor : _lowChanceColor;
	}

