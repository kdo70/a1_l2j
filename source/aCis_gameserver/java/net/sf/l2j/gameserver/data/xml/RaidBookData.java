	@Override
	public void load()
	{
		setDefaultLayout();
		setDefaultColors();
		setDefaultLabels();

		_filters.clear();

		// IXmlReader only catches the parser exceptions ; without this, a single malformed attribute would abort the whole server startup.
		try
		{
			parseFile("./data/xml/raidbook.xml");
		}
		catch (Exception e)
		{
			LOGGER.error("Couldn't fully read raidbook.xml ; the raid boss book runs on whatever has been read so far.", e);
		}

		// Without a single filter the head of the list would hold an empty menu, and no raid boss would ever match.
		if (_filters.isEmpty())
			_filters.add(new LevelFilter("All", 0, 0));
	}

